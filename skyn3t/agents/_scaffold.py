"""Offline scaffold generator.

Produces a *genuinely runnable* minimal project for each known stack as an
in-memory ``{relative_path: contents}`` mapping. The CodeAgent writes these to
disk when the LLM backend is the offline stub, satisfying design rule #1
(delivered != empty) without any network calls.

No I/O happens here — these are pure functions returning dicts of strings.
"""

from __future__ import annotations

import re as _re
from collections.abc import Callable

# ---- README composition ------------------------------------------------------
# A single composer drives every stack's README so each delivered app ships a
# COMPREHENSIVE doc (title + what-it-does from the brief + install + usage +
# features + project structure), not a one-line stub. Each builder supplies the
# stack-specific install/usage/structure; the shared shell guarantees the
# sections and a real description are always present (design rule #1).


def _json_escape(text: str) -> str:
    """Escape a string for safe embedding inside a hand-built JSON literal."""
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").strip()


def _toml_escape(text: str) -> str:
    """Escape a string for a double-quoted TOML basic string."""
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").strip()


def _describe(title: str, brief: str) -> str:
    """One-paragraph "what it does" line drawn from the brief, never a stub."""
    text = (brief or "").strip()
    if not text:
        return f"{title} is an application generated by SkyN3t."
    # Keep the brief verbatim as the description so the README reflects the
    # actual request rather than boilerplate.
    return text[0].upper() + text[1:]


def _features_from_brief(brief: str, defaults: list[str]) -> list[str]:
    """Derive a short feature list from the brief, falling back to stack defaults.

    Splits the brief on common conjunctions/punctuation so a request like
    "tracks todos with due dates and priorities" surfaces as bullet points.
    """
    text = (brief or "").strip()
    if not text:
        return list(defaults)
    parts = _re.split(r"\s*(?:,|;| and | with | that |\.)\s*", text)
    feats = [p.strip().rstrip(".") for p in parts if len(p.strip()) >= 4]
    # De-dupe while preserving order; cap so the list stays scannable.
    seen: set[str] = set()
    out: list[str] = []
    for f in feats:
        key = f.lower()
        if key not in seen:
            seen.add(key)
            out.append(f[0].upper() + f[1:])
    out = out[:6]
    return out or list(defaults)


def compose_readme(
    title: str,
    brief: str,
    *,
    stack_label: str,
    install: str,
    usage: str,
    structure: list[tuple[str, str]],
    features: list[str],
    extra: str = "",
    configuration: str | None = None,
) -> str:
    """Assemble a comprehensive README from stack-specific pieces.

    ``structure`` is a list of ``(path, description)`` rows. ``install`` and
    ``usage`` are pre-formatted markdown blocks (typically fenced code).
    """
    feats = _features_from_brief(brief, features)
    desc = _describe(title, brief)
    lines: list[str] = [f"# {title}", ""]
    # Avoid printing the description twice when the title already IS the brief.
    if desc.strip().lower() != title.strip().lower():
        lines += [desc, ""]
    lines += [
        f"Built with **{stack_label}**. Generated by SkyN3t — a runnable, self-contained starter.",
        "",
        "## Features",
        "",
    ]
    lines += [f"- {f}" for f in feats]
    lines += [
        "",
        "## Installation",
        "",
        install.rstrip(),
        "",
        "## Usage",
        "",
        usage.rstrip(),
        "",
        "## Project structure",
        "",
    ]
    for path, desc in structure:
        lines.append(f"- `{path}` — {desc}")
    if extra:
        lines += ["", extra.rstrip()]
    config_text = configuration or (
        "Configuration is read once at startup from environment variables. Any required "
        "variables are listed in `.env.example`; if a required variable is missing the "
        "app fails fast with a single clear error at startup, rather than silently "
        "falling back to broken behaviour. Copy `.env.example` to `.env`, fill in your "
        "values, and never commit real secrets."
    )
    lines += [
        "",
        "## Configuration",
        "",
        config_text,
        "",
        "## Development",
        "",
        "This project ships with a test suite. Run it after making changes to keep "
        "the app green.",
        "",
        "---",
        "_Generated offline by SkyN3t. Edit freely — it's yours._",
        "",
    ]
    return "\n".join(lines)


# ---- Three.js template detection --------------------------------------------
# Three.js is NOT a stack — it's a TEMPLATE variant of the react/static web
# scaffolds. When the brief implies 3D/WebGL we swap the starter component/page
# for a rotating-cube Three.js scene and add ``three`` as a dependency. The guard
# is keyword-based so ordinary react/static builds are completely unchanged.
_THREEJS_KEYWORDS = ("three.js", "threejs", "three js", "webgl", "3d", "3-d")


