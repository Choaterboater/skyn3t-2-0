def scaffold_for(
    stack: str, app_name: str, brief: str = "", *, art: bool = False
) -> dict[str, str]:
    """Return a ``{path: contents}`` mapping for a runnable project of ``stack``.

    Unknown stacks fall back to ``react_vite``. When the brief implies 3D/WebGL,
    the react/static web scaffolds ship a Three.js rotating-cube starter (a
    template variant, not a separate stack). ``art=True`` (game stacks) makes the
    scaffold preload role sprites and render them with a colored-primitive
    fallback; it never touches the pure sim core.
    """
    safe_name = (app_name or "app").strip() or "app"
    # Three.js template variant: keyword-guarded so normal builds are unchanged.
    if _implies_3d(brief):
        if stack == "react_vite":
            return _react_vite_threejs(safe_name, brief)
        if stack == "static_html":
            return _static_threejs(safe_name, brief)
    # Finance/paper-trading variant (wave-2 §3.4): a strategy/portfolio brief
    # on the fastapi stack gets the paper-trading scaffold. Checked BEFORE
    # market-data: the finance trigger is the higher-precision one (strong
    # phrases / context-gated), so a trading brief that names its data source
    # ("… using live market data") still gets strategy+ledger, while a pure
    # data-API brief ("a quotes api for my trading bot") never fires finance.
    if stack == "fastapi" and _implies_finance(brief):
        return _fastapi_finance(safe_name, brief)
    # Market-data variant (wave-2 §3.9): a data-service brief on the fastapi
    # stack gets the vendor-seam scaffold instead of the bare hello-API.
    if stack == "fastapi" and _implies_market_data(brief):
        return _fastapi_market_data(safe_name, brief)
    # Memory-chat variant (wave-2 §3.10): a "remembers me" brief on the rag
    # stack gets the persistent-memory-journal scaffold.
    if stack == "rag" and _implies_memory_chat(brief):
        return _rag_memory_chat(safe_name, brief)
    # LLM-gateway variant (wave-2 §3.7): a router/proxy brief on the fastapi
    # stack gets the two-stub-upstream gateway scaffold.
    if stack == "fastapi" and _implies_llm_gateway(brief):
        return _fastapi_llm_gateway(safe_name, brief)
    # Terminal-copilot variant (wave-2 §3.6): an agent-CLI brief on the
    # python_cli stack gets the typed-event-stream scaffold.
    if stack == "python_cli" and _implies_cli_agent(brief):
        return _python_cli_agent(safe_name, brief)
    # Supabase variant: a precise Supabase auth/database/backend brief on the
    # nextjs stack gets client-safe Supabase env wiring.
    if stack == "nextjs" and _implies_supabase(brief):
        return _nextjs_supabase(safe_name, brief)
    if stack == "phaser":
        return _phaser(safe_name, brief, art=art)
    builder = _BUILDERS.get(stack, _react_vite)
    return builder(safe_name, brief)


# ---- entrypoint synthesis (repair an agentic build with no runnable root) ----
# A coding agent often authors a real package (foo/manager.py, foo/cli.py, …)
# but forgets the runnable ROOT the rest of the pipeline (proof, boot, reviewer)
# expects. These pure helpers detect that and synthesize a real, wired
# ``main.py`` so ``python main.py`` actually runs the produced code — instead of
# the old behaviour of papering over it with an empty stub.

_ENTRYPOINT_BASENAMES = frozenset(
    {"main.py", "__main__.py", "app.py", "cli.py", "run.py", "manage.py", "wsgi.py", "asgi.py"}
)
# Module-level only (no leading indent): an indented ``def main(self)`` inside a
# class is a method, not an importable ``from module import main`` symbol.
_DEF_ENTRY_RE = _re.compile(r"^def\s+(main|run|cli)\s*\(", _re.MULTILINE)


def _norm(rel: str) -> str:
    return rel.replace("\\", "/")


def _module_path(rel: str) -> str:
    rel = _norm(rel)
    return rel[:-3].replace("/", ".") if rel.endswith(".py") else rel


def has_python_entrypoint(files: dict[str, str]) -> bool:
    """True if any file looks like a runnable Python entrypoint."""
    for rel in files:
        base = _norm(rel).rsplit("/", 1)[-1]
        if base in _ENTRYPOINT_BASENAMES:
            return True
    return False


def top_level_packages(files: dict[str, str]) -> list[str]:
    """Names of depth-1 packages (a dir directly holding ``__init__.py``)."""
    pkgs = {
        _norm(rel).split("/")[0]
        for rel in files
        if len(_norm(rel).split("/")) == 2 and _norm(rel).endswith("/__init__.py")
    }
    return sorted(pkgs)


def _find_entry_callable(files: dict[str, str]) -> tuple[str, str] | None:
    """Find a ``module, func`` exposing a callable named main/run/cli."""

    def rank(rel: str) -> int:
        base = _norm(rel).rsplit("/", 1)[-1]
        return {"cli.py": 0, "__main__.py": 1, "app.py": 2, "main.py": 3}.get(base, 9)

    for rel in sorted(files, key=rank):
        if not _norm(rel).endswith(".py"):
            continue
        m = _DEF_ENTRY_RE.search(files[rel] or "")
        if m:
            return _module_path(rel), m.group(1)
    return None


def synthesize_python_entrypoint(files: dict[str, str]) -> dict[str, str]:
    """Return ``{"main.py": <shim>}`` wiring an existing package to a root runner.

    Returns ``{}`` when the tree already has an entrypoint or there is nothing to
    wire. The shim imports the produced code so ``python main.py`` is genuinely
    runnable (and importable by the boot/proof checks).
    """
    if has_python_entrypoint(files):
        return {}
    target = _find_entry_callable(files)
    pkgs = top_level_packages(files)
    if target is None and not pkgs:
        return {}

    if target is not None:
        module, func = target
        shim = (
            '"""Application entrypoint (auto-wired by SkyN3t).\n\n'
            f"Delegates to ``{module}.{func}`` so ``python main.py`` runs the app.\n"
            '"""\n'
            "from __future__ import annotations\n\n"
            f"from {module} import {func} as _entry\n\n\n"
            "def main(argv: list[str] | None = None) -> int:\n"
            "    result = _entry()\n"
            "    return result if isinstance(result, int) else 0\n\n\n"
            'if __name__ == "__main__":\n'
            "    raise SystemExit(main())\n"
        )
        return {"main.py": shim}

    pkg = pkgs[0]
    shim = (
        '"""Application entrypoint (auto-generated by SkyN3t).\n\n'
        f"Best-effort runner: imports the ``{pkg}`` package and invokes its\n"
        "main()/run()/cli() if one exists.\n"
        '"""\n'
        "from __future__ import annotations\n\n"
        "import importlib\n\n"
        "_MODULES = (\n"
        f'    "{pkg}.cli",\n'
        f'    "{pkg}.__main__",\n'
        f'    "{pkg}.main",\n'
        f'    "{pkg}.app",\n'
        f'    "{pkg}",\n'
        ")\n"
        '_FUNCS = ("main", "run", "cli")\n\n\n'
        "def _resolve():\n"
        "    for name in _MODULES:\n"
        "        try:\n"
        "            mod = importlib.import_module(name)\n"
        "        except Exception:\n"
        "            continue\n"
        "        for fn in _FUNCS:\n"
        "            cand = getattr(mod, fn, None)\n"
        "            if callable(cand):\n"
        "                return cand\n"
        "    return None\n\n\n"
        "def main(argv: list[str] | None = None) -> int:\n"
        "    entry = _resolve()\n"
        "    if entry is None:\n"
        f'        print("{pkg}: imported OK, but no main()/run()/cli() entrypoint was found.")\n'
        "        return 0\n"
        "    result = entry()\n"
        "    return result if isinstance(result, int) else 0\n\n\n"
        'if __name__ == "__main__":\n'
        "    raise SystemExit(main())\n"
    )
    return {"main.py": shim}


def default_pyproject(slug: str) -> str:
    """A minimal but real pyproject for a python project keyed off the slug."""
    name = (slug or "app").strip() or "app"
    return (
        "[project]\n"
        f'name = "{name}"\n'
        'version = "0.1.0"\n'
        'requires-python = ">=3.10"\n\n'
        "[project.scripts]\n"
        f'{name} = "main:main"\n'
    )
