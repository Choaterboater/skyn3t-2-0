"""The Ship pillar — turn a proven build into a concrete plan to go live.

skyn3t builds + proves + previews LOCALLY (``app_runner`` is localhost-only).
This module classifies a build and emits a KEYLESS, one-command deploy plan:
the right hosts, the exact command, and — for server stacks — a ready Dockerfile.
No token, no network: it is the honest "…and here's how it ships" answer for
every stack the builder can produce, or an honest "not a hosted app" verdict.

Registry-driven (the same idiom as ``core.stacks``): every builder stack maps to
a deploy KIND, so a new stack is never silently un-shippable. Real, token-gated
one-command deploy (invoking the emitted command) is a later slice; this is the
foundation and it is fully offline-provable.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from time import time
from typing import Any

# stack (agent vocab + planner aliases) -> deploy kind. Every KNOWN_STACKS entry
# is present (a drift test asserts it). Kinds:
#   static    — a built static bundle → a static host (Cloudflare Pages/Netlify)
#   node_ssr  — a full-stack Node app → Vercel / a Node container
#   container — an HTTP server → Fly / Railway / Render (Dockerfile emitted)
#   artifact  — not a hosted URL: a publishable/runnable binary or package
#   mobile    — an app binary → Expo EAS
DEPLOY_KIND: dict[str, str] = {
    # static-hostable web builds
    "react_vite": "static", "react": "static",
    "static_html": "static", "static": "static",
    "astro": "static", "phaser": "static",
    # full-stack Node (SSR/routing) — not a plain static drop
    "nextjs": "node_ssr", "next": "node_ssr", "remix": "node_ssr",
    # HTTP servers → container
    "fastapi": "container", "rag": "container", "workflow": "container",
    "node_express": "container", "express": "container",
    # not web-hosted: distributable artifacts
    "python_cli": "artifact", "python": "artifact", "cli": "artifact",
    "agent_pack": "artifact", "mcp": "artifact",
    "swift": "artifact", "tauri": "artifact", "desktop": "artifact",
    # mobile app binary
    "react_native": "mobile",
}

_PY_DOCKERFILE = (
    "# Generated by skyn3t — a container image for this FastAPI/Python server.\n"
    "FROM python:3.11-slim\n"
    "WORKDIR /app\n"
    "COPY requirements.txt ./\n"
    "RUN pip install --no-cache-dir -r requirements.txt\n"
    "COPY . .\n"
    "# Platforms (Fly/Railway/Render) inject $PORT; main.py reads it.\n"
    "ENV PORT=8080\n"
    "EXPOSE 8080\n"
    'CMD ["python", "main.py"]\n'
)

_NODE_DOCKERFILE = (
    "# Generated by skyn3t — a container image for this Node server.\n"
    "FROM node:20-slim\n"
    "WORKDIR /app\n"
    "COPY package*.json ./\n"
    "RUN npm ci --omit=dev || npm install --omit=dev\n"
    "COPY . .\n"
    "ENV PORT=8080\n"
    "EXPOSE 8080\n"
    'CMD ["node", "src/index.js"]\n'
)


@dataclass(slots=True)
class DeployPlan:
    """A concrete, keyless plan to put a build on the internet (or distribute it)."""

    deployable: bool = False
    kind: str = "none"
    targets: list[str] = field(default_factory=list)
    command: str = ""
    build_command: str = ""
    output_dir: str = "."
    artifacts: dict[str, str] = field(default_factory=dict)
    serves_url: bool = False
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "deployable": self.deployable,
            "kind": self.kind,
            "targets": list(self.targets),
            "command": self.command,
            "build_command": self.build_command,
            "output_dir": self.output_dir,
            "artifacts": dict(self.artifacts),
            "serves_url": self.serves_url,
            "notes": self.notes,
        }


def _normalize(stack: str) -> str:
    s = (stack or "").strip().lower()
    if s in DEPLOY_KIND:
        return s
    try:
        from skyn3t.agents._common import _normalize_stack

        return _normalize_stack(s) or s
    except Exception:  # noqa: BLE001 - deploy planning must never raise
        return s


def _detect_kind(project_dir: Path, stack: str) -> str:
    """The deploy kind for a stack; when the stack is unknown/empty, fall back to
    content detection via the same run-spec the local preview uses."""
    norm = _normalize(stack)
    if norm in DEPLOY_KIND:
        return DEPLOY_KIND[norm]
    try:
        from skyn3t.studio.app_runner import build_run_spec

        spec = build_run_spec(project_dir, stack, port=0)
    except Exception:  # noqa: BLE001
        spec = None
    if spec is None:
        return "none"
    if spec.kind == "python_web":
        return "container"
    if spec.kind == "static":
        return "static"
    if spec.kind == "node":
        return "node_ssr" if _is_ssr_node(project_dir) else "static"
    return "none"


def _has_build_script(project_dir: Path) -> bool:
    pkg = project_dir / "package.json"
    if not pkg.exists():
        return False
    try:
        scripts = (json.loads(pkg.read_text(encoding="utf-8")) or {}).get("scripts") or {}
    except (OSError, ValueError):
        return False
    return "build" in scripts


def _is_ssr_node(project_dir: Path) -> bool:
    """True when a Node project is a server-rendered framework (Next.js/Remix)
    rather than a plain static SPA (Vite/CRA). Modern Next uses
    ``next.config.mjs``/``.ts`` or *no* config at all, so checking only
    ``next.config.js`` (the old code) misclassifies most current Next apps as
    static and would route them to a static host — breaking SSR/API routes. We
    check config files AND package.json deps/scripts."""
    for name in ("next.config.js", "next.config.mjs", "next.config.ts",
                 "next.config.cjs", "remix.config.js"):
        if (project_dir / name).exists():
            return True
    pkg = project_dir / "package.json"
    if not pkg.exists():
        return False
    try:
        data = json.loads(pkg.read_text(encoding="utf-8")) or {}
    except (OSError, ValueError):
        return False
    deps = {**(data.get("dependencies") or {}), **(data.get("devDependencies") or {})}
    if "next" in deps or any(k.startswith("@remix-run/") for k in deps):
        return True
    scripts = " ".join(str(v) for v in (data.get("scripts") or {}).values())
    return bool(re.search(r"\b(next|remix)\b", scripts))


def _apply_target(requested: str | None, pairs: list[tuple[str, str]]) -> tuple[list[str], str, str]:
    """Honor a user's ``--target`` preference. ``pairs`` is an ordered list of
    ``(host, deploy-command)``; the first is the default. Returns
    ``(ordered_targets, command, note_suffix)``: when ``requested`` is a valid
    host for this kind it is moved to the front and its command is chosen; when
    it is given but unavailable, the default is kept and a note explains why;
    when it is empty, the default order/command is returned unchanged."""
    names = [p[0] for p in pairs]
    cmds = dict(pairs)
    if requested and requested in cmds:
        ordered = [requested] + [n for n in names if n != requested]
        return ordered, cmds[requested], ""
    note = ""
    if requested and requested not in cmds:
        note = (f" (requested target '{requested}' isn't available for this build; "
                f"using {names[0]})")
    return names, cmds[names[0]], note


def plan_deploy(project_dir: str | Path, stack: str = "", *, target: str | None = None) -> DeployPlan:
    """Classify ``project_dir`` and return a keyless :class:`DeployPlan`. Never
    raises; a missing dir or unknown stack still yields a sane plan.

    ``target`` is an optional preferred host (e.g. ``"vercel"``, ``"fly"``):
    when it is a valid host for the detected kind it is moved to the front of
    ``targets`` and its host-specific ``command`` is chosen; an unavailable
    target keeps the default and is explained in ``notes``."""
    try:
        pdir = Path(project_dir)
        kind = _detect_kind(pdir, stack)

        if kind == "static":
            built = _has_build_script(pdir)
            out = "dist" if built else "."
            targets, command, note = _apply_target(target, [
                ("cloudflare-pages", f"npx wrangler pages deploy {out}"),
                ("netlify", f"npx netlify deploy --prod --dir {out}"),
                ("vercel", "npx vercel deploy --prod"),
            ])
            return DeployPlan(
                deployable=True, kind="static", serves_url=True,
                targets=targets, output_dir=out,
                build_command="npm run build" if built else "",
                command=command,
                notes="A static bundle — deploy the built output to any static host." + note,
            )

        if kind == "node_ssr":
            targets, command, note = _apply_target(target, [
                ("vercel", "npx vercel deploy --prebuilt"),
                ("railway", "railway up"),
                ("fly", "fly launch --now"),
            ])
            return DeployPlan(
                deployable=True, kind="node_ssr", serves_url=True,
                targets=targets, output_dir=".", build_command="npm run build",
                command=command,
                notes="A full-stack Node app — Vercel is zero-config; Railway/Fly work via a Node container." + note,
            )

        if kind == "container":
            norm = _normalize(stack)
            dockerfile = _NODE_DOCKERFILE if norm in ("node_express", "express") else _PY_DOCKERFILE
            targets, command, note = _apply_target(target, [
                ("fly", "fly launch --dockerfile Dockerfile --now"),
                ("railway", "railway up"),
                ("render", "render blueprint launch"),
            ])
            return DeployPlan(
                deployable=True, kind="container", serves_url=True,
                targets=targets, output_dir=".", build_command="",
                command=command,
                artifacts={"Dockerfile": dockerfile},
                notes="An HTTP server — ships as a container. Set any keys as platform secrets." + note,
            )

        if kind == "mobile":
            targets, command, note = _apply_target(target, [
                ("expo-eas", "eas build --platform all"),
            ])
            return DeployPlan(
                deployable=True, kind="mobile", serves_url=False,
                targets=targets, output_dir=".", build_command="",
                command=command,
                notes="A mobile app — build stores/installable binaries via Expo EAS." + note,
            )

        if kind == "artifact":
            norm = _normalize(stack)
            if norm in ("python_cli", "python", "cli", "mcp"):
                pairs = [
                    ("pypi", "python -m build && python -m twine upload dist/*"),
                    ("github-release", "gh release create v0.1.0 dist/*"),
                ]
                output = "dist"
            else:  # agent_pack, swift, tauri, desktop
                pairs = [("github-release", "gh release create v0.1.0 <built-artifact>")]
                output = "."
            targets, command, note = _apply_target(target, pairs)
            return DeployPlan(
                deployable=True, kind="artifact", serves_url=False,
                targets=targets, output_dir=output, build_command="",
                command=command,
                notes="Not a hosted URL — a distributable package/binary. Publish, don't serve." + note,
            )

        return DeployPlan(deployable=False, kind="none",
                          notes="No hosted deploy path detected for this build.")
    except Exception as exc:  # noqa: BLE001 - a planner must never break a build
        return DeployPlan(deployable=False, kind="none", notes=f"deploy planning error: {exc}")


def write_deploy_artifacts(plan: DeployPlan, project_dir: str | Path) -> list[str]:
    """Write the plan's artifacts (e.g. a Dockerfile) into the project — but
    NEVER clobber a user-authored file of the same name. Returns the names
    written. Never raises."""
    written: list[str] = []
    pdir = Path(project_dir)
    for name, content in (plan.artifacts or {}).items():
        target = pdir / name
        if target.exists():
            continue  # non-destructive: respect a hand-authored file
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            written.append(name)
        except OSError:
            continue
    return written


def record_deployment(
    project_dir: str | Path,
    *,
    result: dict[str, Any],
    plan: DeployPlan,
    target: str,
) -> dict[str, Any]:
    """Persist a successful live deployment onto the build manifest.

    The record is append-only under ``extra.deployments`` and the latest URL is
    mirrored to ``extra.live_url`` for dashboards that only need the current link.
    Never raises; returns the record it attempted to persist.
    """
    url = str((result or {}).get("url") or "")
    record = {
        "ts": time(),
        "target": str(target or (result or {}).get("target") or ""),
        "provider": str((result or {}).get("target") or ""),
        "url": url,
        "kind": plan.kind,
        "serves_url": bool(plan.serves_url),
    }
    try:
        from skyn3t.studio.manifest import BuildManifest

        pdir = Path(project_dir)
        manifest = BuildManifest.load(pdir)
        if manifest is None:
            return record
        deployments = manifest.extra.get("deployments")
        if not isinstance(deployments, list):
            deployments = []
        deployments.append(record)
        manifest.extra["deployments"] = deployments[-20:]
        if url:
            manifest.extra["live_url"] = url
        manifest.save(pdir)
    except Exception:  # noqa: BLE001 - recording must not make deploy fail
        pass
    return record
