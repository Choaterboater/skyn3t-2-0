function normalizeText(value) {
  return String(value).replaceAll("\r\n", "\n").trimEnd() + "\n";
}

function repositoryUrl(pkg) {
  const raw = typeof pkg.repository === "string"
    ? pkg.repository
    : pkg.repository?.url || pkg.homepage || "";
  return String(raw)
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/\.git$/, "");
}

function hasRuntimeCode(packageDir, pkg) {
  if (String(pkg.name || "").startsWith("@types/")) return false;
  if (pkg.main || pkg.module || pkg.browser || pkg.exports || pkg.bin) return true;
  return ["index.js", "index.mjs", "index.cjs"].some((name) =>
    existsSync(join(packageDir, name))
  );
}

function localLicense(packageDir) {
  const candidates = readdirSync(packageDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^licen[sc]e(?:[.\-_]|$)/i.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  if (!candidates.length) return null;
  return normalizeText(readFileSync(join(packageDir, candidates[0]), "utf8"));
}

const lock = JSON.parse(readFileSync(LOCK_PATH, "utf8"));
const notices = [];

for (const [packagePath, lockEntry] of Object.entries(lock.packages || {})) {
  if (!packagePath.startsWith("node_modules/") || lockEntry.dev || lockEntry.optional) {
    continue;
  }

  const packageDir = join(UI_ROOT, packagePath);
  const pkg = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
  if (!hasRuntimeCode(packageDir, pkg)) continue;

  const fallback = LICENSE_FALLBACKS[pkg.name];
  const licenseText = localLicense(packageDir) || fallback?.text;
  if (!licenseText) {
    throw new Error(`No redistributable license text found for ${pkg.name}@${pkg.version}`);
  }

  notices.push({
    id: `${pkg.name}@${pkg.version}`,
    license: pkg.license || lockEntry.license || "UNKNOWN",
    source: fallback?.source || repositoryUrl(pkg),
    text: normalizeText(licenseText),
  });
}

notices.sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));

const divider = "=".repeat(79);
const sections = notices.map((notice) => [
  divider,
  notice.id,
  `License: ${notice.license}`,
  notice.source ? `Source: ${notice.source}` : "",
  "-".repeat(79),
  notice.text.trimEnd(),
].filter(Boolean).join("\n"));

const output = normalizeText([
  "SkyN3t Dashboard Third-Party Notices",
  "",
  "Generated by scripts/generate-third-party-notices.mjs from the locked",
  "non-development packages that expose runtime JavaScript entry points.",
  "Do not edit this file manually.",
  "",
  `Packages: ${notices.length}`,
  "",
  ...sections,
].join("\n"));

const previous = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, "utf8") : "";
if (previous !== output) writeFileSync(OUTPUT_PATH, output, "utf8");
console.log(`Wrote ${notices.length} third-party notices to ${OUTPUT_PATH}`);
